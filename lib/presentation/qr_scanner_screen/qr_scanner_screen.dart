class QrScannerScreen extends StatefulWidget {
  const QrScannerScreen({super.key});

  @override
  State<QrScannerScreen> createState() => _QrScannerScreenState();
}

class _QrScannerScreenState extends State<QrScannerScreen>
    with TickerProviderStateMixin {
  bool _isProcessing = false;
  final MobileScannerController _scannerController = MobileScannerController(
    detectionSpeed: DetectionSpeed.noDuplicates,
    formats: const [BarcodeFormat.qrCode],
  );

  late AnimationController _scanLineController;
  late Animation<double> _scanLineAnimation;

  @override
  void initState() {
    super.initState();
    _scanLineController = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 2000),
    )..repeat(reverse: true);

    _scanLineAnimation = Tween<double>(begin: 0.0, end: 1.0).animate(
      CurvedAnimation(parent: _scanLineController, curve: Curves.easeInOut),
    );
  }

  void _onDetect(BarcodeCapture capture) {
    if (_isProcessing) return;
    final List<Barcode> barcodes = capture.barcodes;
    for (final barcode in barcodes) {
      // Strictly accept only QR codes (reject 1D barcodes like EAN, UPC, Code128, etc.)
      if (barcode.format != BarcodeFormat.qrCode) continue;
      final code = barcode.rawValue;
      if (code != null && code.trim().isNotEmpty) {
        _processQrCode(code);
        break;
      }
    }
  }

  Future<void> _processQrCode(String code) async {
    if (_isProcessing) return;
    setState(() => _isProcessing = true);

    try {
      final cleanCode = code.trim();
      final normalized =
          cleanCode.toUpperCase().replaceAll('_', '-').replaceAll(' ', '');

      // 1. Check if matches a registered park by QR code, ID, or Name
      final park = await SupabaseService.instance.getParkByQrCode(cleanCode);
      if (!mounted) return;

      if (park != null) {
        Fluttertoast.showToast(
          msg: 'Parc identifié: ${park['name'] ?? 'RTH Sonatrach'}',
          backgroundColor: AppTheme.success,
          textColor: Colors.white,
          gravity: ToastGravity.TOP,
          toastLength: Toast.LENGTH_SHORT,
        );

        context.go(
          AppRoutes.parkHomeScreen,
          extra: {
            'role': 'User',
            'parkId': park['id'] as String?,
          },
        );
        return;
      }

      // 2. Direct recognition of user's generated QR code (me-qr.com / rm1fhboz)
      if (cleanCode.toLowerCase().contains('rm1fhboz')) {
        Fluttertoast.showToast(
          msg: 'Parc RTH Sonatrach identifié',
          backgroundColor: AppTheme.success,
          textColor: Colors.white,
          gravity: ToastGravity.TOP,
          toastLength: Toast.LENGTH_SHORT,
        );
        context.go(
          AppRoutes.parkHomeScreen,
          extra: {'role': 'User'},
        );
        return;
      }

      // 3. Comprehensive check for official park codes or app URL QR codes
      if (normalized.contains('TRC-RTH') ||
          normalized.contains('RTH-PARK') ||
          normalized.contains('PARK-001') ||
          normalized.contains('TRCRTH') ||
          normalized.contains('RTHPARK') ||
          cleanCode.toLowerCase().contains('badereddinehaitham.github.io/trc_rth') ||
          cleanCode.toLowerCase().contains('trc_rth')) {
        Fluttertoast.showToast(
          msg: 'Parc RTH Sonatrach identifié',
          backgroundColor: AppTheme.success,
          textColor: Colors.white,
          gravity: ToastGravity.TOP,
          toastLength: Toast.LENGTH_SHORT,
        );
        context.go(
          AppRoutes.parkHomeScreen,
          extra: {'role': 'User'},
        );
        return;
      }

      // 4. Resolve web URLs generated by online QR generators
      if (cleanCode.startsWith('http://') || cleanCode.startsWith('https://')) {
        try {
          final dio = Dio(BaseOptions(
            connectTimeout: const Duration(milliseconds: 2500),
            receiveTimeout: const Duration(milliseconds: 2500),
            followRedirects: true,
          ));
          final res = await dio.get(cleanCode);
          final bodyText = res.data.toString().toUpperCase();
          if (bodyText.contains('TRC-RTH') ||
              bodyText.contains('RTH-PARK') ||
              bodyText.contains('PARK-001') ||
              bodyText.contains('TRC_RTH')) {
            if (!mounted) return;
            Fluttertoast.showToast(
              msg: 'Parc RTH Sonatrach identifié',
              backgroundColor: AppTheme.success,
              textColor: Colors.white,
              gravity: ToastGravity.TOP,
              toastLength: Toast.LENGTH_SHORT,
            );
            context.go(
              AppRoutes.parkHomeScreen,
              extra: {'role': 'User'},
            );
            return;
          }
        } catch (_) {}
      }

      // 3. Check if QR code matches a specific registered vehicle
      final vehicle = await SupabaseService.instance.getVehicleByCode(cleanCode);
      if (!mounted) return;

      if (vehicle != null) {
        Fluttertoast.showToast(
          msg: 'Véhicule identifié: ${vehicle['name'] ?? ''}',
          backgroundColor: AppTheme.success,
          textColor: Colors.white,
          gravity: ToastGravity.TOP,
          toastLength: Toast.LENGTH_SHORT,
        );

        context.go(
          AppRoutes.vehicleDetailsScreen,
          extra: {
            'vehicleId': vehicle['id'] as String,
            'role': 'User',
          },
        );
        return;
      }

      // Unknown or unrelated QR code -> Reject and show scanned value
      _onInvalidScan(cleanCode);
    } catch (e) {
      if (mounted) {
        _onInvalidScan(code);
      }
    } finally {
      if (mounted) {
        setState(() => _isProcessing = false);
      }
    }
  }

  void _onInvalidScan(String code) {
    final display = code.trim();
    final truncated =
        display.length > 25 ? '${display.substring(0, 22)}...' : display;
    Fluttertoast.showToast(
      msg: 'QR Code non reconnu: "$truncated"',
      backgroundColor: AppTheme.critical,
      textColor: Colors.white,
      gravity: ToastGravity.TOP,
      toastLength: Toast.LENGTH_LONG,
    );
  }

  void _showManualEntry() {
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (ctx) => ManualEntryWidget(
        onSubmit: (code) {
          Navigator.pop(ctx);
          _processQrCode(code);
        },
      ),
    );
  }

  @override
  void dispose() {
    _scanLineController.dispose();
    _scannerController.dispose();
    super.dispose();
  }

