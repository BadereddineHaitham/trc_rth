                          Text(
                            'Scannez le QR Code officiel',
                            style: GoogleFonts.ibmPlexSans(
                              color: Colors.white.withAlpha(204),
                              fontSize: 13,
                              fontWeight: FontWeight.w500,
                            ),
                          ),
                        ],
                      ),
                    ),
                  ),

